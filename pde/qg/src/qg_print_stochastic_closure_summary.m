function qg_print_stochastic_closure_summary(result)

gal = result.metrics_gal;
moi = result.metrics_moi_sde;
closure = result.metrics_closure_sde;

fprintf('\n==================== CPOpInf COMPARISON =======================\n');
fprintf('r = %d\n', result.r);
fprintf('Metric                                G-ROM      CPOpInf-NC      CPOpInf-EC\n');
fprintf('--------------------------------------------------------------------------\n');
fprintf('Relative trajectory Frobenius    %11.4e   %11.4e   %11.4e\n', ...
    gal.relative_trajectory_frobenius, ...
    moi.relative_trajectory_frobenius, ...
    closure.relative_trajectory_frobenius);
fprintf('Mean-streamfunction L2           %11.4e   %11.4e   %11.4e\n', ...
    gal.mean_streamfunction_l2, moi.mean_streamfunction_l2, ...
    closure.mean_streamfunction_l2);
fprintf('Relative kinetic-energy L2       %11.4e   %11.4e   %11.4e\n', ...
    gal.relative_energy_l2, moi.relative_energy_l2, ...
    closure.relative_energy_l2);
fprintf('Mean normalized mode RMSE        %11.4e   %11.4e   %11.4e\n', ...
    mean(gal.mode_normalized_rmse), mean(moi.mode_normalized_rmse), ...
    mean(closure.mode_normalized_rmse));
fprintf('Mean mode correlation            %11.4e   %11.4e   %11.4e\n', ...
    mean(gal.mode_correlation), mean(moi.mode_correlation), ...
    mean(closure.mode_correlation));
fprintf('--------------------------------------------------------------------------\n');
fprintf('CPOpInf-EC constraint residual:   %.4e\n', ...
    result.closure.constraint_residual);
fprintf('CPOpInf-EC active coefficients:   %d / %d\n', ...
    nnz(result.closure.active), numel(result.closure.active));
fprintf('CPOpInf-EC diffusion range:       [%.4e, %.4e]\n', ...
    min(result.closure.sigma), max(result.closure.sigma));
fprintf('==========================================================================\n\n');
end
