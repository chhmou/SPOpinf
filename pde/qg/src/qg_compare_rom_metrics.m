function metrics = qg_compare_rom_metrics( ...
    par_qg, filenames, w_ref, w_model, Er, r)

difference = w_ref - w_model;
reference_rms = sqrt(mean(w_ref.^2, 2));
model_rms_error = sqrt(mean(difference.^2, 2));

dev_ref = w_ref - mean(w_ref, 2);
dev_model = w_model - mean(w_model, 2);
corr_denominator = sqrt(sum(dev_ref.^2, 2) .* sum(dev_model.^2, 2));

ke_ref = qg_cal_ke(w_ref, Er);
ke_model = qg_cal_ke(w_model, Er);
mean_psi_error_squared = qg_cal_mean_psi_err( ...
    par_qg, filenames, w_model, r);

metrics = struct( ...
    'relative_trajectory_frobenius', ...
        norm(difference, 'fro') / max(norm(w_ref, 'fro'), eps), ...
    'mean_streamfunction_l2', sqrt(mean_psi_error_squared), ...
    'mean_streamfunction_l2_squared', mean_psi_error_squared, ...
    'relative_energy_l2', ...
        norm(ke_model - ke_ref) / max(norm(ke_ref), eps), ...
    'mode_normalized_rmse', model_rms_error ./ max(reference_rms, eps), ...
    'mode_correlation', sum(dev_ref .* dev_model, 2) ./ ...
        max(corr_denominator, eps), ...
    'kinetic_energy', ke_model);
end
