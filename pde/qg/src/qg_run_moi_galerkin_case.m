function result = qg_run_moi_galerkin_case( ...
    cfg, w_proj, qg_operator, r, options)

par_qg = cfg.par_qg;
filenames = cfg.filenames;

[B_gal, C_gal, D_gal] = qg_galerkin_to_polynomial( ...
    par_qg, qg_operator, r);
wr0 = w_proj(1:r, 1);
wr_gal = qg_rom_fun(par_qg, filenames, qg_operator, wr0, r);

dt_data = par_qg.ddt * par_qg.save_index;
n_available_pairs = size(w_proj, 2) - 1;
n_training_pairs = min(options.n_training_pairs, n_available_pairs);
pair_index = unique(round(linspace( ...
    1, n_available_pairs, n_training_pairs)));
u_train_physical = w_proj(1:r, pair_index);
z_train_physical = (w_proj(1:r, pair_index + 1) - ...
    u_train_physical) / dt_data;

if isfield(options, 'use_global_state_scale') && ...
        options.use_global_state_scale
    state_scale = sqrt(mean(u_train_physical.^2, 'all'));
else
    state_scale = 1;
end
u_train = u_train_physical / state_scale;
z_res = (z_train_physical - D_gal) / state_scale;

[H_constraint, nonzero_index] = qg_build_moi_constraints(r);
n_theta = numel(nonzero_index);
theta_par = zeros(n_theta, 1);

normal_matrix_gib = (8 * n_theta^2) / 1024^3;
fprintf('Training r=%d with %d pairs and %d coefficients.\n', ...
    r, numel(pair_index), n_theta);
fprintf('Unchanged solver dense normal matrix alone: approximately %.2f GiB.\n', ...
    normal_matrix_gib);
fprintf('Uniform state scale supplied to optimizer: %.6e.\n', state_scale);

[theta_moi, R_update, active] = em_stochastic_solver_sparse( ...
    u_train, z_res, r, numel(pair_index), theta_par, ...
    H_constraint, nonzero_index, options.tol, dt_data, ...
    options.sparsity_thresh, options.Gamma, ...
    options.Niter_em, options.Niter_stlsq);

[B_moi_scaled, C_moi] = qg_moi_vec_to_operators(theta_moi, r);
B_moi = B_moi_scaled / state_scale;
D_moi = D_gal;
sigma_moi = state_scale * sqrt(max(diag(R_update) * dt_data, 0));

[wr_moi_drift, wr_moi_sde] = qg_moi_rom_fun( ...
    par_qg, B_moi, C_moi, D_moi, sigma_moi, wr0, ...
    options.rng_seed + r);

n_save = size(wr_gal, 2);
t_rom = par_qg.t0 + (0:n_save-1) * ...
    par_qg.ddt * par_qg.save_index;
w_ref = w_proj(1:r, 1:n_save);

metrics_gal = qg_compare_rom_metrics( ...
    par_qg, filenames, w_ref, wr_gal, qg_operator.Er, r);
metrics_moi_drift = qg_compare_rom_metrics( ...
    par_qg, filenames, w_ref, wr_moi_drift, qg_operator.Er, r);
metrics_moi_sde = qg_compare_rom_metrics( ...
    par_qg, filenames, w_ref, wr_moi_sde, qg_operator.Er, r);

operator_errors = struct( ...
    'relative_B', norm(B_moi(:) - B_gal(:)) / ...
        max(norm(B_gal(:)), eps), ...
    'relative_C', norm(C_moi - C_gal, 'fro') / ...
        max(norm(C_gal, 'fro'), eps), ...
    'max_constraint_residual', max(abs(H_constraint * theta_moi)), ...
    'active_coefficients', nnz(active), ...
    'total_coefficients', numel(active));

result = struct( ...
    'r', r, ...
    'optimization_options', options, ...
    'state_scale', state_scale, ...
    'dt_data', dt_data, ...
    'pair_index', pair_index, ...
    'chosen_modes', unique(round(linspace(1, r, min(4, r)))), ...
    't_rom', t_rom, ...
    'w_ref', w_ref, ...
    'wr_gal', wr_gal, ...
    'wr_moi_drift', wr_moi_drift, ...
    'wr_moi_sde', wr_moi_sde, ...
    'B_gal', B_gal, 'C_gal', C_gal, 'D_gal', D_gal, ...
    'B_moi', B_moi, 'C_moi', C_moi, 'D_moi', D_moi, ...
    'theta_moi', theta_moi, ...
    'R_update', R_update, ...
    'sigma_moi', sigma_moi, ...
    'active', active, ...
    'Er', qg_operator.Er, ...
    'metrics_gal', metrics_gal, ...
    'metrics_moi_drift', metrics_moi_drift, ...
    'metrics_moi_sde', metrics_moi_sde, ...
    'operator_errors', operator_errors);
end
