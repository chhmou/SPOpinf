function qg_print_moi_galerkin_summary(result)

gal = result.metrics_gal;
drift = result.metrics_moi_drift;
sde = result.metrics_moi_sde;
op = result.operator_errors;

fprintf('\n==================== COMPARISON SUMMARY =======================\n');
fprintf('r = %d\n', result.r);
fprintf('Metric                                G-ROM       MOI drift       MOI SDE\n');
fprintf('----------------------------------------------------------------\n');
fprintf('Relative trajectory Frobenius    %11.4e   %11.4e   %11.4e\n', ...
    gal.relative_trajectory_frobenius, ...
    drift.relative_trajectory_frobenius, ...
    sde.relative_trajectory_frobenius);
fprintf('Mean-streamfunction L2           %11.4e   %11.4e   %11.4e\n', ...
    gal.mean_streamfunction_l2, drift.mean_streamfunction_l2, ...
    sde.mean_streamfunction_l2);
fprintf('Relative kinetic-energy L2       %11.4e   %11.4e   %11.4e\n', ...
    gal.relative_energy_l2, drift.relative_energy_l2, ...
    sde.relative_energy_l2);
fprintf('Mean normalized mode RMSE        %11.4e   %11.4e   %11.4e\n', ...
    mean(gal.mode_normalized_rmse), ...
    mean(drift.mode_normalized_rmse), ...
    mean(sde.mode_normalized_rmse));
fprintf('Mean mode correlation            %11.4e   %11.4e   %11.4e\n', ...
    mean(gal.mode_correlation), mean(drift.mode_correlation), ...
    mean(sde.mode_correlation));
fprintf('----------------------------------------------------------------\n');
fprintf('MOI-vs-Galerkin relative B error: %.4e\n', op.relative_B);
fprintf('MOI-vs-Galerkin relative C error: %.4e\n', op.relative_C);
fprintf('MOI constraint residual:          %.4e\n', ...
    op.max_constraint_residual);
fprintf('MOI active coefficients:          %d / %d\n', ...
    op.active_coefficients, op.total_coefficients);
fprintf('Inferred diffusion range:         [%.4e, %.4e]\n', ...
    min(result.sigma_moi), max(result.sigma_moi));
fprintf('================================================================\n\n');
end
