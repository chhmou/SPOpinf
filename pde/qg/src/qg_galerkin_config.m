function cfg = qg_galerkin_config(project_dir, data_root)

if nargin == 0 || isempty(project_dir)
    project_dir = fileparts(fileparts(mfilename('fullpath')));
end

if nargin < 2 || isempty(data_root) || strcmp(data_root, '<path to data>')
    error('qg_galerkin_config:dataPath', ...
        'Set dataPath at the top of the QG driver to the folder that contains FOM/ and test1/.');
end
source_root = data_root;
legacy_data_root = data_root;
legacy_test_root = fullfile(legacy_data_root, 'test1');

t0 = 10;
t1 = 80;
ddt = 1e-3;
save_index = 10;
n_time = round((t1 - t0) / ddt);

Ro = 0.0036;
Re = 450;
nx = 257;
ny = 513;
dx = 1 / 256;
dy = 1 / 256;
xgrid = 0:dx:1;
ygrid = 0:dy:2;

W = simpson_2D_weights(nx, ny, dx, dy);
weight = W(:);

par_qg = struct( ...
    'ddt', ddt, ...
    'n_time', n_time, ...
    'save_index', save_index, ...
    't0', t0, ...
    't1', t1, ...
    'xmin', 0, ...
    'xmax', 1, ...
    'ymin', 0, ...
    'ymax', 2, ...
    'dx', dx, ...
    'dy', dy, ...
    'nx', nx, ...
    'ny', ny, ...
    'xgrid', xgrid, ...
    'ygrid', ygrid, ...
    'W', W, ...
    'weight', weight, ...
    'N_dof', nx * ny, ...
    'Ro', Ro, ...
    'Re', Re, ...
    'N_snap', 3500, ...
    'Mo_pod', 100);

filenames = struct( ...
    'fom_data', fullfile(legacy_data_root, 'FOM', 'w_snap.mat'), ...
    'mean_data', fullfile(legacy_data_root, 'FOM', 'mean_data.mat'), ...
    'pod_data', fullfile(legacy_test_root, 'pod_fd_m3500.mat'), ...
    'fom_proj_data', fullfile(legacy_test_root, ...
        'qge_proj_data_npod3500_re450_ro3p6en03.mat'), ...
    'cache_root', fullfile(project_dir, 'data_cache'), ...
    'results_root', fullfile(project_dir, 'results_qg_galerkin_rom'));

required_files = {filenames.mean_data, filenames.pod_data, ...
    filenames.fom_proj_data};
for k = 1:numel(required_files)
    assert(exist(required_files{k}, 'file') == 2, ...
        'Required input file not found: %s', required_files{k});
end

cfg = struct('par_qg', par_qg, 'filenames', filenames, ...
    'source_root', source_root);
end
