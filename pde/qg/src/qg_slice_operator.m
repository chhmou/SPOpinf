function qg_operator_r = qg_slice_operator(qg_operator_max, r)

r_max = size(qg_operator_max.Mr, 1);
validateattributes(r, {'numeric'}, ...
    {'scalar', 'integer', 'positive', '<=', r_max});

qg_operator_r = struct( ...
    'Mr', qg_operator_max.Mr(1:r, 1:r), ...
    'Mr_x', qg_operator_max.Mr_x(1:r, 1:r), ...
    'Sr', qg_operator_max.Sr(1:r, 1:r), ...
    'fr', qg_operator_max.fr(1:r), ...
    'Tyx', qg_operator_max.Tyx(1:r, 1:r, 1:r), ...
    'Txy', qg_operator_max.Txy(1:r, 1:r, 1:r));

if isfield(qg_operator_max, 'Er')
    qg_operator_r.Er = qg_operator_max.Er(1:r, 1:r);
end
end
