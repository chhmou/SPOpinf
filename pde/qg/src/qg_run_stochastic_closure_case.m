function result = qg_run_stochastic_closure_case( ...
    cfg, w_proj, qg_operator, direct_moi_result, r, options)

par_qg = cfg.par_qg;
filenames = cfg.filenames;

[B_gal, C_gal, D_gal] = qg_galerkin_to_polynomial( ...
    par_qg, qg_operator, r);
wr0 = w_proj(1:r, 1);

closure = qg_train_stochastic_closure( ...
    par_qg, w_proj, B_gal, C_gal, D_gal, r, options);
wr_closure_sde = qg_stochastic_closure_rom_fun( ...
    par_qg, B_gal, C_gal, D_gal, closure, wr0, ...
    options.rng_seed + r);

n_save = size(direct_moi_result.wr_gal, 2);
w_ref = w_proj(1:r, 1:n_save);
metrics_closure_sde = qg_compare_rom_metrics( ...
    par_qg, filenames, w_ref, wr_closure_sde, qg_operator.Er, r);

result = struct( ...
    'method_version', 2, ...
    'r', r, 't_rom', direct_moi_result.t_rom, 'w_ref', w_ref, ...
    'wr_gal', direct_moi_result.wr_gal, ...
    'wr_moi_sde', direct_moi_result.wr_moi_sde, ...
    'wr_closure_sde', wr_closure_sde, ...
    'metrics_gal', direct_moi_result.metrics_gal, ...
    'metrics_moi_sde', direct_moi_result.metrics_moi_sde, ...
    'metrics_closure_sde', metrics_closure_sde, ...
    'B_gal', B_gal, 'C_gal', C_gal, 'D_gal', D_gal, ...
    'closure', closure, 'Er', qg_operator.Er, ...
    'chosen_modes', unique(round(linspace(1, r, min(4, r)))));
end
