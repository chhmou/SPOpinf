function closure = qg_train_stochastic_closure( ...
    par_qg, w_proj, B_gal, C_gal, D_gal, r, options)

dt_data = par_qg.ddt * par_qg.save_index;
n_available_pairs = size(w_proj, 2) - 1;
n_training_pairs = min(options.n_training_pairs, n_available_pairs);
pair_index = unique(round(linspace( ...
    1, n_available_pairs, n_training_pairs)));

u_physical = w_proj(1:r, pair_index);
da_dt_physical = (w_proj(1:r, pair_index + 1) - u_physical) / dt_data;
galerkin_at_data = zeros(r, numel(pair_index));
for sample = 1:numel(pair_index)
    galerkin_at_data(:, sample) = qg_polynomial_drift( ...
        u_physical(:, sample), B_gal, C_gal, D_gal);
end

closure_target_physical = da_dt_physical - galerkin_at_data;

if isfield(options, 'use_global_state_scale') && ...
        options.use_global_state_scale
    state_scale = sqrt(mean(u_physical.^2, 'all'));
else
    state_scale = 1;
end
u_train = u_physical / state_scale;
z_closure = closure_target_physical / state_scale;

[H_constraint, nonzero_index] = qg_build_moi_constraints(r);
n_theta = numel(nonzero_index);
theta_initial = zeros(n_theta, 1);

normal_matrix_gib = (8 * n_theta^2) / 1024^3;
fprintf('Training stochastic closure at r=%d with %d pairs and %d coefficients.\n', ...
    r, numel(pair_index), n_theta);
fprintf('Closure target: da/dt - f_Galerkin(a).\n');
fprintf('Unchanged solver dense normal matrix alone: approximately %.2f GiB.\n', ...
    normal_matrix_gib);
fprintf('Uniform state scale supplied to optimizer: %.6e.\n', state_scale);

[theta_closure, R_update, active] = em_stochastic_solver_sparse( ...
    u_train, z_closure, r, numel(pair_index), theta_initial, ...
    H_constraint, nonzero_index, options.tol, dt_data, ...
    options.sparsity_thresh, options.Gamma, ...
    options.Niter_em, options.Niter_stlsq);

[B_closure_scaled, C_closure] = qg_moi_vec_to_operators( ...
    theta_closure, r);
B_closure = B_closure_scaled / state_scale;
D_closure = zeros(r, 1);
sigma_closure = state_scale * sqrt(max(diag(R_update) * dt_data, 0));

closure = struct( ...
    'B', B_closure, 'C', C_closure, 'D', D_closure, ...
    'theta', theta_closure, 'R_update', R_update, ...
    'sigma', sigma_closure, 'active', active, ...
    'constraint_residual', max(abs(H_constraint * theta_closure)), ...
    'state_scale', state_scale, 'dt_data', dt_data, ...
    'pair_index', pair_index, ...
    'target_rms', sqrt(mean(closure_target_physical.^2, 2)), ...
    'optimization_options', options);
end
