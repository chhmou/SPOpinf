function phi = buildFeatures(a)
a  = a(:);
r  = numel(a);
nq = r*(r+1)/2;
quad = zeros(nq,1);
idx = 0;
for i = 1:r
    for j = i:r
        idx = idx + 1;
        quad(idx) = a(i)*a(j);
    end
end
phi = [quad; a];
end
