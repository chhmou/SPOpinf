  1 4 1 +1;  2 3 1 -1;  3 6 1 +1;  4 5 1 -1;
  1 3 2 -1;  2 4 2 -1;  3 5 2 -1;  4 6 2 -1;
  1 2 3 +2;  1 6 3 +2;  2 5 3 -2;
