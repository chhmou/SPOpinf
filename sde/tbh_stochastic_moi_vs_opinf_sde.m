function [B_est, C_est, D_est] = vecToOperators(theta, dim)
col_u1_shift = dim*dim*(dim+1)/2;
col_u2_shift = dim*dim;

B_vec = theta(1:col_u1_shift);
C_vec = theta(col_u1_shift+1 : col_u1_shift+col_u2_shift);
