function r = acfFast(x, maxlag)
x = x(:)' - mean(x);
n = numel(x);
nfft = 2^nextpow2(n + maxlag);
f = fft(x, nfft);
c = ifft(abs(f).^2);
r = real(c(1:maxlag+1)) / max(real(c(1)), eps);
end

