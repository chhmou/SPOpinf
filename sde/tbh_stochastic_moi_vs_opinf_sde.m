function M = complexPatternMatrix()
pat = { ...
 [1 3 1 1 0; 2 4 1 1 0; 1 4 1 0 -1; 2 3 1 0 1; ...
  1 4 2 1 0; 2 3 2 -1 0; 1 3 2 0 1; 2 4 2 0 1], ...
 [3 5 1 1 0; 4 6 1 1 0; 3 6 1 0 -1; 4 5 1 0 1; ...
  3 6 2 1 0; 4 5 2 -1 0; 3 5 2 0 1; 4 6 2 0 1], ...
 [1 1 3 1 0; 2 2 3 -1 0; 1 2 3 0 -2; ...
  1 2 4 2 0; 1 1 4 0 1; 2 2 4 0 -1], ...
 [1 5 3 1 0; 2 6 3 1 0; 1 6 3 0 -1; 2 5 3 0 1; ...
  1 6 4 1 0; 2 5 4 -1 0; 1 5 4 0 1; 2 6 4 0 1], ...
 [1 3 5 1 0; 2 4 5 -1 0; 1 4 5 0 -1; 2 3 5 0 -1; ...
  1 4 6 1 0; 2 3 6 1 0; 1 3 6 0 1; 2 4 6 0 -1]};
M = zeros(6^3, 10);
for m = 1:5
    P = pat{m};
    for r = 1:size(P,1)
        li = P(r,1) + 6*(P(r,2)-1) + 36*(P(r,3)-1);
        M(li, 2*m-1) = M(li, 2*m-1) + P(r,4);
        M(li, 2*m  ) = M(li, 2*m  ) + P(r,5);
    end
end
end

function [c_hat, resid] = recoverComplexCoeffs(B_est)
M = complexPatternMatrix();
b = B_est(:);
theta = M \ b;
c_hat = theta(1:2:end) + 1i*theta(2:2:end);
resid = norm(b - M*theta) / max(norm(b), eps);
end

function [lam_hat, offblk] = recoverComplexDampings(C_est)
lam_hat = zeros(3,1);
mask = true(6,6);
for k = 1:3
    ix = 2*k-1 : 2*k;
    Blk = C_est(ix, ix);
    mu    = (Blk(1,1) + Blk(2,2))/2;
    omega = (Blk(2,1) - Blk(1,2))/2;
    lam_hat(k) = mu + 1i*omega;
    mask(ix, ix) = false;
end
offblk = max(abs(C_est(mask)));
end

