clear; clc

K      = 3;
nu     = 0.5;
s_cplx = 0.5;
s_real = s_cplx/sqrt(2);

dt      = 0.005;
T       = 1000;
N       = round(T/dt);

dim      = 2*K;
Ttrans   = 20;
rng_seed = 10;

c_truth      = [-1i; -1i; -1i; -2i; -3i];
lambda_truth = -nu*ones(3,1);

nlc = @(u) [ -1i*( conj(u(1))*u(2) + conj(u(2))*u(3) ) ;
             -1i*( u(1)^2          + 2*conj(u(1))*u(3) ) ;
             -3i*  u(1)*u(2) ];

rng(rng_seed);
sqdt = sqrt(dt);
Uc = zeros(3, N);
Uc(:,1) = 0.1*(randn(3,1) + 1i*randn(3,1));
for n = 1:N-1
    u  = Uc(:,n);
    xi = (randn(3,1) + 1i*randn(3,1))/sqrt(2);
    Uc(:,n+1) = u + (nlc(u) - nu*u)*dt + s_cplx*sqdt*xi;
end
U = zeros(dim, N);
U(1:2:end,:) = real(Uc);
U(2:2:end,:) = imag(Uc);
t_save = (0:N-1)*dt;
fprintf('Training data generated by the COMPLEX model, mapped to real.\n');

out_dir = fullfile(fileparts(mfilename('fullpath')), '..', 'data');
if ~exist(out_dir, 'dir'), mkdir(out_dir); end
out_file = fullfile(out_dir, 'tbh_training_data.mat');
save(out_file, 'U', 'Uc', 't_save', 'dt', 'T', 'N', 'dim', 'Ttrans', 'rng_seed', 'K', 'nu', 's_cplx', 's_real', 'c_truth', 'lambda_truth');
fprintf('Saved %d snapshots (dim = %d, dt = %g) to %s\n', size(U, 2), size(U, 1), dt, out_file);
